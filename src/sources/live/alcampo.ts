/**
 * Alcampo (www.compraonline.alcampo.es): live search, read from the state the page ships.
 *
 * The shop runs on the Ocado platform behind CloudFront + AWS WAF. Its pages embed the
 * data they render as JSON (`window.__INITIAL_STATE__ = {…}`, `window.__QUERY_INITIAL_STATE__ = {…}`);
 * we read prices from there, never from a private API.
 *
 * robots.txt (https://www.compraonline.alcampo.es/robots.txt, read 2026-11-15) — the lines this
 * module relies on:
 *
 *   User-agent: *
 *   Disallow: /sso-login
 *   Disallow: /basket
 *   Disallow: /delivery/      (also /delivery$ and /delivery?)
 *   Disallow: /checkout/      (also /checkout$ and /checkout?)
 *   Disallow: *?sortBy=
 *   Disallow: *&sortBy=
 *
 * `/search?q=…` is not disallowed, and we never add `sortBy`. Product links point at
 * `/products/<slug>/<id>`, which is not disallowed either.
 *
 * Politeness: one request per search() (kind 'search', so http.ts spaces it, sends the honest
 * user agent and caches it 6 h). A 403/429 or a WAF/CloudFront challenge page throws
 * BlockedError: we never retry, and never pretend to be a browser. From the cloud test machine
 * the search answered 403 "Request blocked … Generated by cloudfront" on 2026-11-15
 * (test/fixtures/alcampo/blocked-403.html).
 *
 * VERIFIED ONLY AGAINST PRODUCT-PAGE STATE. The search page could not be fetched, so its state
 * shape was never seen. Parsing is generic on purpose: every object in any `window.__…__ = {…}`
 * assignment that carries `retailerProductId`, `name` and `price.amount` is an offer (first 12,
 * de-duplicated by `retailerProductId`). On the product page we saw (test/fixtures/alcampo/
 * product-page.html) the product sits in `__QUERY_INITIAL_STATE__.queries[].state.data.product`;
 * the Ocado search page is expected to fill `__INITIAL_STATE__.data.products.productEntities`
 * with objects of the same shape — unverified.
 */
import type { Offer, PriceUnit } from '../../shared/types';
import { parseSize, sizeFromName, unitPriceCents } from '../../shared/units';
import { BlockedError, type AdapterCtx, type ChainAdapter } from './types';

export const ALCAMPO_BASE = 'https://www.compraonline.alcampo.es';
export const ALCAMPO_MAX_OFFERS = 12;

type Json = Record<string, unknown>;

const isObj = (v: unknown): v is Json => typeof v === 'object' && v !== null && !Array.isArray(v);
const str = (v: unknown): string | null => {
  if (typeof v === 'number' && Number.isFinite(v)) return String(v);
  if (typeof v !== 'string') return null;
  const s = v.replace(/\s+/g, ' ').trim();
  return s || null;
};

export function alcampoSearchUrl(query: string): string {
  return `${ALCAMPO_BASE}/search?q=${encodeURIComponent(query.replace(/\s+/g, ' ').trim())}`;
}

