/** "11.28", "11,28 €", 11.28 → 1128; null when not a positive amount. */
export function toCents(v: unknown): number | null {
  let n: number;
  if (typeof v === 'number') n = v;
  else if (typeof v === 'string') {
    let s = v.replace(/[€\s]/g, '');
    if (s.includes(',') && !s.includes('.')) s = s.replace(',', '.');
    else if (s.includes(',') && s.includes('.')) s = s.replace(/\./g, '').replace(',', '.');
    if (!/^\d+(\.\d+)?$/.test(s)) return null;
    n = Number(s);
  } else return null;
  if (!Number.isFinite(n) || n <= 0) return null;
  return Math.round(n * 100);
}

/**
 * An Ocado unit-price key as a factor to €/kg, €/l or €/ud:
 * "fop.price.per.litre" → l ×1, "fop.price.per.100gram" → kg ×10, "fop.price.per.each" → ud ×1,
 * "per.kilogram"/"kg" → kg, "fop.price.per.dozen" → ud ÷12. Other units (wash, dose, metre…) → null.
 */
export function alcampoUnit(key: string): { unit: PriceUnit; factor: number } | null {
  const k = key.toLowerCase().trim().replace(/^.*\bper\./, '').replace(/^per\s*/, '');
  const m = /^(\d+)?\s*(grams?|g|gr|kilograms?|kilos?|kgs?|millilitres?|milliliters?|ml|litres?|liters?|l|lt|centilitres?|cl|each|units?|unidad(?:es)?|ud|dozen)$/.exec(k);
  if (!m) return null;
  const n = m[1] ? Number(m[1]) : 1;
  if (!(n > 0)) return null;
  const u = m[2]!;
  if (/^(grams?|g|gr)$/.test(u)) return { unit: 'kg', factor: 1000 / n };
  if (/^(kilograms?|kilos?|kgs?)$/.test(u)) return { unit: 'kg', factor: 1 / n };
  if (/^(millilitres?|milliliters?|ml)$/.test(u)) return { unit: 'l', factor: 1000 / n };
  if (/^(litres?|liters?|l|lt)$/.test(u)) return { unit: 'l', factor: 1 / n };
  if (/^(centilitres?|cl)$/.test(u)) return { unit: 'l', factor: 100 / n };
  if (u === 'dozen') return { unit: 'ud', factor: 1 / (12 * n) };
  return { unit: 'ud', factor: 1 / n };
}

function absoluteUrl(v: unknown): string | null {
  const s = str(v);
  if (!s) return null;
  try {
    const u = new URL(s, ALCAMPO_BASE);
    return u.protocol === 'https:' || u.protocol === 'http:' ? u.href : null;
  } catch {
    return null;
  }
}

function imageOf(e: Json): string | null {
  const first = Array.isArray(e.images) ? e.images[0] : undefined;
  const path = Array.isArray(e.imagePaths) ? str(e.imagePaths[0]) : null;
  return absoluteUrl(isObj(e.image) ? e.image.src : e.image)
    ?? absoluteUrl(isObj(first) ? first.src : first)
    // Seen in the fixture: image.src is imagePaths[0] + "/300x300.jpg".
    ?? (path ? absoluteUrl(`${path.replace(/\/+$/, '')}/300x300.jpg`) : null)
    ?? absoluteUrl(e.imageUrl);
}

/** Lower-case words joined by dashes, accents dropped — how the site writes its product slugs. */
export function alcampoSlug(name: string): string {
  return name.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function urlOf(e: Json, id: string, name: string): string {
  const slug = str(e.slug) ?? str(e.seoSlug) ?? str(e.urlSlug) ?? alcampoSlug(name);
  const safeId = encodeURIComponent(id);
  return slug && /^[a-z0-9-]+$/i.test(slug)
    ? `${ALCAMPO_BASE}/products/${slug}/${safeId}`
    : `${ALCAMPO_BASE}/products/${safeId}`;
}

function cleanText(v: unknown, max = 80): string | null {
  const s = str(typeof v === 'string' ? v.replace(/<[^>]*>/g, ' ') : v);
  return s ? (s.length > max ? `${s.slice(0, max - 1)}…` : s) : null;
}

function promoOf(e: Json): string | null {
  const lists = [e.promotions, e.promos].filter(Array.isArray) as unknown[][];
  for (const list of lists) {
    for (const p of list) {
      const t = typeof p === 'string' ? cleanText(p)
        : isObj(p) ? cleanText(p.description) ?? cleanText(p.name) ?? cleanText(p.title) ?? cleanText(p.text) ?? cleanText(p.label) : null;
      if (t) return t;
    }
  }
  if (isObj(e.promotion)) return cleanText(e.promotion.description) ?? cleanText(e.promotion.name);
  return cleanText(e.promoText) ?? cleanText(e.promotionText) ?? cleanText(e.offerText);
}

function eanOf(e: Json): string | null {
  for (const k of ['ean', 'gtin', 'gtin13', 'barcode']) {
    const d = str(e[k])?.replace(/\D/g, '') ?? '';
    if (/^\d{8,14}$/.test(d)) return d;
  }
  return null;
}

const ymd = (d: Date): string => d.toISOString().slice(0, 10);

/**
 * The unit price the page shows: `unitPrice: { price: { amount }, unit: "fop.price.per.litre" }`
 * (seen), or `price.unit: { label, current: { amount } }` (other Ocado shops, unverified).
 */
function publishedUnitPrice(e: Json): { cents: number; unit: PriceUnit } | null {
  let amount: unknown;
  let key: string | null = null;
  if (isObj(e.unitPrice)) {
    amount = isObj(e.unitPrice.price) ? e.unitPrice.price.amount : e.unitPrice.amount;
    key = str(e.unitPrice.unit);
  } else if (isObj(e.price) && isObj(e.price.unit)) {
    amount = isObj(e.price.unit.current) ? e.price.unit.current.amount : e.price.unit.amount;
    key = str(e.price.unit.label) ?? str(e.price.unit.unit);
  }
  const cents = toCents(amount);
  const per = key ? alcampoUnit(key) : null;
  return cents !== null && per ? { cents: Math.round(cents * per.factor), unit: per.unit } : null;
}

/** One Ocado product entity as an Offer; null when something we need is missing. */
export function alcampoOffer(e: Json, now: Date): Offer | null {
  const id = str(e.retailerProductId);
  const name = str(e.name);
  if (!id || !name) return null;
  const currency = priceCurrency(e.price);
  if (currency && currency.toUpperCase() !== 'EUR') return null;
  const priceCents = toCents(priceAmount(e.price));
  if (priceCents === null) return null;

  const sizeText = str(e.packSizeDescription) ?? str(e.packSize);
  const unitPrice = publishedUnitPrice(e)
    ?? unitPriceCents(priceCents, parseSize(sizeText) ?? sizeFromName(name));

  return {
    chain: 'alcampo',
    id,
    name,
    brand: str(e.brand),
    ean: eanOf(e),
    sizeText,
    priceCents,
    unitPriceCents: unitPrice?.cents ?? null,
    unit: unitPrice?.unit ?? null,
    image: imageOf(e),
    url: urlOf(e, id, name),
    promo: promoOf(e),
    source: 'live',
    observedOn: ymd(now),
  };
}

/**
 * The offers in an Alcampo page (search or product page): first 12, de-duplicated by
 * retailerProductId. A product that cannot be read is skipped, never thrown.
 */
export function parseAlcampoState(html: string, now: Date): Offer[] {
  return offersFromStates(readPageStates(html), now);
}

function offersFromStates(states: Array<{ value: unknown }>, now: Date): Offer[] {
  const offers: Offer[] = [];
  const seen = new Set<string>();
  for (const { value } of states) {
    for (const e of productEntities(value)) {
      let offer: Offer | null = null;
      try {
        offer = alcampoOffer(e, now);
      } catch {
        offer = null;
      }
      if (!offer || seen.has(offer.id)) continue;
      seen.add(offer.id);
      offers.push(offer);
      if (offers.length >= ALCAMPO_MAX_OFFERS) return offers;
    }
  }
  return offers;
}

/** CloudFront / AWS WAF refusals and challenges (only checked on pages without state). */
const CHALLENGE = /Request blocked|Generated by cloudfront|AwsWafIntegration|gokuProps|challenge\.js|captcha|Access Denied|Too Many Requests/i;

export const alcampo: ChainAdapter = {
  chain: 'alcampo',
  async search(query: string, ctx: AdapterCtx): Promise<Offer[]> {
    const q = query.replace(/\s+/g, ' ').trim();
    if (!q) return [];
    const res = await ctx.fetch(alcampoSearchUrl(q), {
      kind: 'search',
      headers: { accept: 'text/html,application/xhtml+xml' },
    });
    if (res.status === 403 || res.status === 429) {
      await res.body?.cancel().catch(() => undefined);
      throw new BlockedError(res.status, `alcampo: blocked (${res.status})`);
    }
    const html = await res.text();
    if (!res.ok) {
      if (CHALLENGE.test(html)) throw new BlockedError(res.status, `alcampo: challenge page (${res.status})`);
      throw new Error(`alcampo: HTTP ${res.status}`);
    }
    const states = readPageStates(html);
    if (states.length === 0) {
      if (CHALLENGE.test(html)) throw new BlockedError(res.status, 'alcampo: challenge page');
      throw new Error('alcampo: page without product state');
    }
    return offersFromStates(states, ctx.now);
  },
};
