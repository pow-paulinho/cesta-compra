/** The `{…}` that starts at `start`, found by matching braces outside strings; null when unbalanced. */
export function sliceJsonObject(text: string, start: number): string | null {
  if (text.charCodeAt(start) !== 123 /* { */) return null;
  let depth = 0;
  let inString = false;
  for (let i = start; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (inString) {
      if (c === 92 /* \ */) i++;
      else if (c === 34 /* " */) inString = false;
      continue;
    }
    if (c === 34) inString = true;
    else if (c === 123 || c === 91 /* [ */) depth++;
    else if (c === 125 || c === 93 /* ] */) {
      depth--;
      if (depth === 0) return text.slice(start, i + 1);
      if (depth < 0) return null;
    }
  }
  return null;
}

/** A JS string literal starting at `start` ("…" or '…'), returned with its quotes. */
function sliceStringLiteral(text: string, start: number): string | null {
  const q = text[start];
  if (q !== '"' && q !== "'") return null;
  for (let i = start + 1; i < text.length; i++) {
    const c = text[i];
    if (c === '\\') i++;
    else if (c === q) return text.slice(start, i + 1);
  }
  return null;
}

function tryJson(s: string): unknown {
  try {
    return JSON.parse(s);
  } catch {
    return undefined;
  }
}

/**
 * Every `window.__NAME__ = {…}` (or `= JSON.parse("…")`) in the page, parsed, in page order.
 * A value may be followed by `;` and other statements; unparseable ones are skipped.
 */
export function readPageStates(html: string): Array<{ name: string; value: unknown }> {
  const out: Array<{ name: string; value: unknown }> = [];
  const re = /window\.(__[A-Za-z0-9_]+__)\s*=\s*/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(html))) {
    const at = m.index + m[0].length;
    let value: unknown;
    if (html[at] === '{') {
      const raw = sliceJsonObject(html, at);
      if (raw) {
        value = tryJson(raw);
        re.lastIndex = at + raw.length;
      }
    } else if (html.startsWith('JSON.parse(', at)) {
      const lit = sliceStringLiteral(html, at + 'JSON.parse('.length);
      const inner = lit && lit[0] === '"' ? tryJson(lit) : undefined;
      value = typeof inner === 'string' ? tryJson(inner) : undefined;
    }
    if (isObj(value)) out.push({ name: m[1]!, value });
  }
  return out;
}

/**
 * `price.amount` as on the product page we saw; `price.current.amount` as other Ocado shops
 * write it (tolerated, unverified for Alcampo).
 */
function priceAmount(price: unknown): unknown {
  if (!isObj(price)) return undefined;
  if (price.amount !== undefined) return price.amount;
  return isObj(price.current) ? price.current.amount : undefined;
}

function priceCurrency(price: unknown): string | null {
  if (!isObj(price)) return null;
  return str(price.currency) ?? (isObj(price.current) ? str(price.current.currency) : null);
}

/** Objects that look like an Ocado product entity, depth first in document order. */
function* productEntities(root: unknown): Generator<Json> {
  const stack: unknown[] = [root];
  let visited = 0;
  while (stack.length && visited < 500_000) {
    const node = stack.pop();
    visited++;
    if (Array.isArray(node)) {
      for (let i = node.length - 1; i >= 0; i--) stack.push(node[i]);
    } else if (isObj(node)) {
      if ((typeof node.retailerProductId === 'string' || typeof node.retailerProductId === 'number')
        && typeof node.name === 'string' && priceAmount(node.price) !== undefined) {
        yield node;
      }
      const values = Object.values(node);
      for (let i = values.length - 1; i >= 0; i--) {
        const v = values[i];
        // Some Ocado payloads (urql) carry JSON as a string: look inside those too.
        if (typeof v === 'string' && v.length > 20 && v.length < 5_000_000 && v[0] === '{' && v.includes('retailerProductId')) {
          stack.push(tryJson(v));
        } else if (typeof v === 'object' && v !== null) {
          stack.push(v);
        }
      }
    }
  }
}

